"""Run SUMO pilot experiments with ``python -m trafficlab``."""

import argparse
import json
from pathlib import Path

from .controllers import make_controller
from .runner import run_episode
from .scenario import Config, ROOT


def main() -> None:
    parser = argparse.ArgumentParser(description="SUMO traffic decision-model comparison pilot")
    parser.add_argument("--controller", choices=("fixed", "adaptive", "gurobi", "microsoft", "jev", "luna", "sol-medium", "microsoft-rich", "all"), default="fixed")
    parser.add_argument("--duration", type=float, default=300.0, help="simulation seconds")
    parser.add_argument("--horizon", type=int, default=15, help="planning seconds, independent of simulation duration")
    parser.add_argument("--inflow", type=float, default=0.15, help="vehicles/second/approach")
    parser.add_argument("--cav-share", type=float, default=0.5)
    parser.add_argument("--seeds", type=int, nargs="+", default=[7])
    parser.add_argument("--gui", action="store_true", help="show the run in SUMO-GUI")
    parser.add_argument("--web", action="store_true", help="serve a browser replay generated by SUMO")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--speed", type=float, default=1.0, help="GUI replay speed multiplier")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "results" / "single")
    parser.add_argument("--output", type=Path, help="optional JSONL summary file")
    args = parser.parse_args()
    if args.web:
        from .web import serve
        serve(port=args.port)
        return
    names = ("fixed", "adaptive", "gurobi") if args.controller == "all" else (args.controller,)
    if args.gui and (len(names) != 1 or len(args.seeds) != 1):
        parser.error("--gui requires one controller and one seed")
    config_kwargs = dict(duration=args.duration, planning_horizon=args.horizon, inflow_per_approach=args.inflow, cav_share=args.cav_share)
    records = []
    for seed in args.seeds:
        config = Config(seed=seed, **config_kwargs)
        for name in names:
            result = run_episode(config, make_controller(name, horizon=config.planning_horizon), args.output_dir,
                                 gui=args.gui, playback_speed=args.speed)
            records.append(result.record())
            print(json.dumps(records[-1], sort_keys=True))
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text("\n".join(json.dumps(row, sort_keys=True) for row in records) + "\n",
                               encoding="utf-8")
        print(f"Wrote {len(records)} summary row(s) to {args.output}")


if __name__ == "__main__":
    main()
